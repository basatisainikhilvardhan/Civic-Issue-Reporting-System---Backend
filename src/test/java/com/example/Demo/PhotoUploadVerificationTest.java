    private static final String CITIZEN_EMAIL = "upload_test_citizen@civic.org";
    private static final String CITIZEN_PASSWORD = "Password123!";

    private String getUploadUrl() {
        return "http://localhost:" + port + "/api/issues/upload";
    }

    private byte[] generateDecodableImage(String format, int width, int height, boolean addHighEntropyNoise) throws Exception {
        BufferedImage image = new BufferedImage(width, height, BufferedImage.TYPE_INT_RGB);
        if (addHighEntropyNoise) {
            int[] pixels = ((DataBufferInt) image.getRaster().getDataBuffer()).getData();
            Random rnd = new Random(42);
            for (int i = 0; i < pixels.length; i++) {
                pixels[i] = rnd.nextInt();
            }
        } else {
            Graphics2D g = image.createGraphics();
            g.setColor(Color.BLUE);
            g.fillRect(0, 0, width, height);
            g.setColor(Color.WHITE);
            g.drawString("Civic Issue Verification Image", 20, 40);
            g.dispose();
        }

        ByteArrayOutputStream baos = new ByteArrayOutputStream();
        ImageIO.write(image, format, baos);
        byte[] bytes = baos.toByteArray();

        // Verify that the generated bytes are decodable by ImageIO
        BufferedImage verified = ImageIO.read(new ByteArrayInputStream(bytes));
        Assertions.assertNotNull(verified, "Generated test image must be decodable");
        Assertions.assertEquals(width, verified.getWidth());
        Assertions.assertEquals(height, verified.getHeight());

        return bytes;
    }

    @BeforeEach
    void setUp() {
        restTemplate = new RestTemplate(new org.springframework.http.client.JdkClientHttpRequestFactory());

        userRepository.findByEmail(CITIZEN_EMAIL).ifPresent(userRepository::delete);

        testCitizen = new Users();
        testCitizen.setName("Upload Test Citizen");
        testCitizen.setEmail(CITIZEN_EMAIL);
        testCitizen.setPassword(passwordEncoder.encode(CITIZEN_PASSWORD));
        testCitizen.setPhone("9876543210");
        testCitizen.setRole(Role.CITIZEN);
        testCitizen = userRepository.save(testCitizen);
        citizenToken = jwtUtil.generateToken(testCitizen);
    }

    @AfterEach
    void tearDown() {
        if (testCitizen != null && testCitizen.getXyz() != null) {
            userRepository.findById(testCitizen.getXyz()).ifPresent(userRepository::delete);
        }
    }

    @Test
    @DisplayName("1. Genuine, decodable JPEG upload succeeds and is retrievable")
    void testUploadGenuineJpeg_Success() throws Exception {
        byte[] payload = generateDecodableImage("jpg", 2000, 1500, true);

        // Verify generated byte count is under 5 MB
        Assertions.assertNotNull(payload);
        Assertions.assertTrue(payload.length > 500_000, "Generated JPEG should be substantial (>500KB)");
        Assertions.assertTrue(payload.length < 5 * 1024 * 1024, "Generated JPEG byte count must be strictly under 5 MB limit. Actual: " + payload.length);

        ByteArrayResource fileResource = new ByteArrayResource(payload) {
            @Override
            public String getFilename() {
                return "civic_issue_pothole_evidence.jpg";
            }
        };

        HttpHeaders headers = new HttpHeaders();
        headers.setContentType(MediaType.MULTIPART_FORM_DATA);
        headers.setBearerAuth(citizenToken);

        MultiValueMap<String, Object> body = new LinkedMultiValueMap<>();
        body.add("file", fileResource);

        HttpEntity<MultiValueMap<String, Object>> requestEntity = new HttpEntity<>(body, headers);

        ResponseEntity<Map> response = restTemplate.postForEntity(getUploadUrl(), requestEntity, Map.class);

        Assertions.assertEquals(HttpStatus.OK, response.getStatusCode());
        Assertions.assertNotNull(response.getBody());
        Assertions.assertEquals(true, response.getBody().get("success"));
        String imageUrl = (String) response.getBody().get("imageUrl");
        Assertions.assertNotNull(imageUrl);
        Assertions.assertTrue(imageUrl.startsWith("/uploads/"));
        Assertions.assertTrue(imageUrl.endsWith(".jpg"));

        // Verify the file was physically saved and is a valid, decodable JPEG image
        String fileName = imageUrl.replace("/uploads/", "");
        File savedFile = new File("uploads", fileName);
        Assertions.assertTrue(savedFile.exists(), "Uploaded file should exist in uploads directory");
        Assertions.assertEquals(payload.length, savedFile.length(), "Saved file size should match uploaded bytes");

        BufferedImage savedImage = ImageIO.read(savedFile);
        Assertions.assertNotNull(savedImage, "Saved file on disk must be genuinely decodable by ImageIO");
        Assertions.assertEquals(2000, savedImage.getWidth());
        Assertions.assertEquals(1500, savedImage.getHeight());

        // Verify HTTP retrieval of uploaded image via static resource handler
        ResponseEntity<byte[]> getResponse = restTemplate.getForEntity("http://localhost:" + port + imageUrl, byte[].class);
        Assertions.assertEquals(HttpStatus.OK, getResponse.getStatusCode());
        Assertions.assertNotNull(getResponse.getBody());
        Assertions.assertEquals(payload.length, getResponse.getBody().length);

        // Cleanup test file
        savedFile.delete();
    }


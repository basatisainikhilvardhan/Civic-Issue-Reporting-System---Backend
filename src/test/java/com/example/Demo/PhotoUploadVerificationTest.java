    @Test
    @DisplayName("3. Corrupted or non-image binary data labelled as JPEG is rejected with HTTP 400")
    void testUploadCorruptedOrFakeImage_FailsWith400() {
        // Arbitrary binary data (not a decodable image)
        byte[] payload = new byte[65536];

        ByteArrayResource fileResource = new ByteArrayResource(payload) {
            @Override
            public String getFilename() {
                return "disguised_evidence.jpg";
            }
        };

        HttpHeaders headers = new HttpHeaders();
        headers.setContentType(MediaType.MULTIPART_FORM_DATA);
        headers.setBearerAuth(citizenToken);

        MultiValueMap<String, Object> body = new LinkedMultiValueMap<>();
        body.add("file", fileResource);

        HttpEntity<MultiValueMap<String, Object>> requestEntity = new HttpEntity<>(body, headers);

        try {
            restTemplate.postForEntity(getUploadUrl(), requestEntity, Map.class);
            Assertions.fail("Expected HTTP 400 Bad Request for corrupted/pseudo image");
        } catch (HttpClientErrorException e) {
            Assertions.assertEquals(HttpStatus.BAD_REQUEST, e.getStatusCode());
            String responseBody = e.getResponseBodyAsString();
            Assertions.assertTrue(responseBody.toLowerCase().contains("image"), "Error message should mention image content rejection");
        }
    }

    @Test
    @DisplayName("4. Oversized image exceeding 5 MB limit is rejected with HTTP 413")
    void testUploadImage_Exceeding5MB_FailsWith413() {
        // 5.5 MB payload (exceeds 5 MB limit)
        int sizeBytes = (int) (5.5 * 1024 * 1024);
        byte[] payload = new byte[sizeBytes];

        ByteArrayResource fileResource = new ByteArrayResource(payload) {
            @Override
            public String getFilename() {
                return "oversized_photo.jpg";
            }
        };

        HttpHeaders headers = new HttpHeaders();
        headers.setContentType(MediaType.MULTIPART_FORM_DATA);
        headers.setBearerAuth(citizenToken);

        MultiValueMap<String, Object> body = new LinkedMultiValueMap<>();
        body.add("file", fileResource);

        HttpEntity<MultiValueMap<String, Object>> requestEntity = new HttpEntity<>(body, headers);

        try {
            restTemplate.postForEntity(getUploadUrl(), requestEntity, Map.class);
            Assertions.fail("Expected HTTP 413 Content/Payload Too Large");
        } catch (HttpClientErrorException e) {
            Assertions.assertEquals(413, e.getStatusCode().value());
            Assertions.assertTrue(e.getResponseBodyAsString().contains("Photo file size exceeds maximum limit of 5 MB."));
        }
    }

